"""End-to-end review orchestration.

Stages: validate -> deck -> models -> match -> checks -> reports -> done.
Each stage reports progress through an optional callback so the web UI can show
it. Input problems raise :class:`NumCheckInputError` with an actionable hint;
everything else that reduces coverage becomes a :class:`ReviewWarning`.
"""

from __future__ import annotations

import logging
import os
import time
from collections.abc import Callable
from pathlib import Path

from numcheck.checks import IssueCollector, run_checks
from numcheck.checks.coverage import compute_coverage
from numcheck.checks.issues import build_issues, finalize_issues
from numcheck.config import Config, load_config
from numcheck.extraction.pptx_extractor import extract_deck_full
from numcheck.extraction.xlsx_extractor import extract_model_full
from numcheck.matching.pipeline import match_deck_to_model
from numcheck.models import (
    DeckExtraction,
    ModelExtraction,
    NumCheckInputError,
    ReviewResult,
    ReviewWarning,
)

log = logging.getLogger(__name__)

ProgressFn = Callable[[str, float, str], None]

REPORT_FILES = {
    "html": "report.html",
    "xlsx": "report.xlsx",
    "json": "report.json",
    "deck": "deck_flagged.pptx",
}


def run_review(
    deck_path: str,
    model_paths: list[str],
    model_old_path: str | None = None,
    out_dir: str = "report",
    annotate: bool = True,
    config: Config | None = None,
    ocr: bool = False,
    progress: ProgressFn | None = None,
    input_names: dict | None = None,
) -> ReviewResult:
    """Review *deck_path* against *model_paths* and write all reports to *out_dir*.

    ``input_names`` lets callers (the web app) show original upload names instead
    of the safe on-disk names: ``{"deck": str, "models": [str], "model_old": str}``.
    """
    config = config or load_config()
    if ocr:
        config.ocr = True
    report = _progress(progress)
    start = time.time()
    warnings: list[ReviewWarning] = []

    report("validate", 0.02, "Validating files")
    if not model_paths:
        raise NumCheckInputError("At least one model workbook is required.")

    report("deck", 0.08, "Reading deck")
    deck = extract_deck_full(deck_path, config)
    if config.ocr:
        from numcheck.extraction.ocr_extractor import extract_deck_ocr

        deck.numbers.extend(extract_deck_ocr(deck_path, existing=deck.numbers, warnings=warnings))
    warnings.extend(deck.warnings)
    if not deck.numbers:
        warnings.append(ReviewWarning(
            "no_deck_numbers",
            "No checkable numbers were found in the deck. If the numbers are pictures, enable OCR.",
            file=_name(deck_path),
        ))

    report("models", 0.25, "Reading models")
    model_values = []
    sheets = []
    seen_names: dict[str, int] = {}
    for i, path in enumerate(model_paths):
        report("models", 0.25 + 0.2 * i / max(len(model_paths), 1), f"Reading {_name(path)}")
        ext = extract_model_full(path, config)
        _dedupe_workbook_name(ext, seen_names)
        model_values.extend(ext.values)
        sheets.extend(ext.sheets)
        warnings.extend(ext.warnings)
    if not model_values:
        warnings.append(ReviewWarning(
            "no_model_values",
            "No numeric values were found in the model(s). If the workbook was generated by code, "
            "open it in Excel and save it so formula results are stored.",
        ))

    old_values = []
    if model_old_path:
        report("models", 0.45, "Reading previous model")
        old = extract_model_full(model_old_path, config)
        old_values = old.values
        warnings.extend(w for w in old.warnings if w.code != "uncalculated_formulas")

    report("match", 0.5, f"Matching {len(deck.numbers)} numbers against {len(model_values):,} cells")
    matches = match_deck_to_model(
        deck.numbers, model_values, config,
        old_model_values=old_values or None, slides=deck.slides, warnings=warnings,
    )

    for m in matches:
        # Targets/guidance ("management targets a 10-12% margin from new platforms") are forward-looking
        # statements: a difference from the model is not an error, only unverifiable.
        if m.status == "mismatch" and "guidance" in (m.deck.qualifiers or []) and m.method != "named_range":
            m.status = "unmatched"
            m.note = (m.note + "; " if m.note else "") + "forward-looking target/guidance differs from the model"
    try:
        from numcheck.matching.derived import verify_derived

        verify_derived(matches, model_values, config, slides=deck.slides)
    except Exception:  # noqa: BLE001 - an optional enrichment must not abort the review
        log.exception("derived verification failed")
        warnings.append(ReviewWarning("derived_failed", "Derived growth/margin verification was skipped."))

    report("checks", 0.72, "Running checks")
    collector = IssueCollector(config)
    build_issues(matches, config, collector, slides=deck.slides)
    run_checks(deck.numbers, matches, deck.slides, deck.footnotes, config, collector)
    issues = finalize_issues(collector.issues, config, slides=deck.slides)
    _fill_display_text(issues, deck.numbers, config)

    coverage = compute_coverage(matches, deck)
    _fill_issue_counts(coverage, issues)

    result = ReviewResult(
        issues=issues,
        matches=matches,
        warnings=_dedupe_warnings(warnings),
        slides=deck.slides,
        sheets=sheets,
        coverage=coverage,
        deck_numbers=len(deck.numbers),
        model_values=len(model_values),
        inputs=_inputs(deck_path, model_paths, model_old_path, input_names),
        settings=_settings(config),
    )

    report("reports", 0.85, "Writing reports")
    _write_reports(result, deck_path, out_dir, annotate)
    result.elapsed = time.time() - start
    # The HTML/JSON reports carry elapsed time: rewrite them now that it is known.
    _write_reports(result, deck_path, out_dir, annotate=False, only_text=True)
    report("done", 1.0, f"{len(issues)} issue(s) found")
    return result


# --------------------------------------------------------------------------- #


def _progress(fn: ProgressFn | None) -> ProgressFn:
    def report(stage: str, fraction: float, message: str) -> None:
        log.info("[%s] %s", stage, message)
        if fn is not None:
            try:
                fn(stage, fraction, message)
            except Exception:  # noqa: BLE001 - a broken progress callback must not kill the run
                log.debug("progress callback failed", exc_info=True)
    return report


def _write_reports(result: ReviewResult, deck_path: str, out_dir: str, annotate: bool,
                   only_text: bool = False) -> None:
    from numcheck.report.excel_report import write_excel_report
    from numcheck.report.html_report import write_html_report
    from numcheck.report.json_report import write_json_report

    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    writers = [("html", write_html_report), ("json", write_json_report)]
    if not only_text:
        writers.append(("xlsx", write_excel_report))
    for key, writer in writers:
        path = out / REPORT_FILES[key]
        try:
            writer(result, path)
            result.files[key] = str(path)
        except Exception as exc:  # noqa: BLE001 - one report failing must not lose the others
            log.exception("writing %s failed", key)
            result.warnings.append(ReviewWarning("report_failed", f"Could not write {path.name}: {exc}"))
    if annotate and not only_text:
        from numcheck.report.annotate_pptx import annotate_deck

        path = out / REPORT_FILES["deck"]
        try:
            failures = annotate_deck(deck_path, str(path), result)
            result.files["deck"] = str(path)
            if failures:
                result.warnings.append(ReviewWarning(
                    "annotation_partial",
                    f"The annotated deck could not mark {len(failures)} item(s): " + "; ".join(failures[:3]),
                    count=len(failures),
                ))
        except Exception as exc:  # noqa: BLE001
            log.exception("annotation failed")
            result.warnings.append(ReviewWarning("annotation_failed", f"Could not write the annotated deck: {exc}"))


def _name(path: str | None) -> str:
    return os.path.basename(path) if path else ""


def _dedupe_workbook_name(ext: ModelExtraction, seen: dict[str, int]) -> None:
    """Two uploaded models with the same file name must stay distinguishable in cell refs."""
    name = ext.workbook or ""
    n = seen.get(name, 0)
    seen[name] = n + 1
    if n == 0:
        return
    stem, dot, suffix = name.rpartition(".")
    new = f"{stem} ({n + 1}).{suffix}" if dot else f"{name} ({n + 1})"
    ext.workbook = new
    for v in ext.values:
        v.workbook = new
        v.uid = f"{new}|{v.sheet_name}!{v.cell_address}"


def _dedupe_warnings(warnings: list[ReviewWarning]) -> list[ReviewWarning]:
    seen: set[tuple] = set()
    out = []
    for w in warnings:
        key = (w.code, w.message, w.file, w.slide_number, w.sheet)
        if key in seen:
            continue
        seen.add(key)
        out.append(w)
    return out


def _fill_display_text(issues, numbers, config) -> None:
    """Express each issue's difference/tolerance in its deck number's own units."""
    from numcheck.matching.normalizer import format_difference, format_tolerance

    by_uid = {d.uid: d for d in numbers if d.uid}
    by_pos = {(d.slide_number, d.raw_text): d for d in numbers}
    for i in issues:
        d = by_uid.get(i.deck_uid) or by_pos.get((i.slide_number, i.deck_value))
        if d is None:
            continue
        ref = i.details.get("model_canonical") if isinstance(i.details, dict) else None
        if ref is None and i.difference is not None:
            from numcheck.matching.normalizer import canonical_deck, parsed_from_deck

            ref = canonical_deck(parsed_from_deck(d), config.unit_scales)[1] - i.difference
        try:
            if i.difference is not None and not i.difference_text:
                i.difference_text = format_difference(d, i.difference, ref or 0.0, config)
            if i.tolerance is not None and not i.tolerance_text:
                i.tolerance_text = format_tolerance(d, i.tolerance, ref or 0.0, config)
        except (ValueError, ZeroDivisionError, OverflowError):
            continue


def _fill_issue_counts(coverage: dict, issues) -> None:
    per = {}
    for i in issues:
        per[i.slide_number] = per.get(i.slide_number, 0) + 1
    for row in coverage.get("per_slide", []):
        row["issues"] = per.get(row.get("slide_number"), 0)


def _inputs(deck_path, model_paths, model_old_path, names: dict | None) -> dict:
    names = names or {}
    return {
        "deck": names.get("deck") or _name(deck_path),
        "models": names.get("models") or [_name(p) for p in model_paths],
        "model_old": names.get("model_old") or _name(model_old_path),
    }


def _settings(config: Config) -> dict:
    """Effective settings for the report header. Never includes secrets."""
    return {
        "llm": config.llm or "off",
        "model": config.model_name if (config.llm or "off") != "off" else "",
        "rounding_mode": config.rounding_mode,
        "extra_relative_tolerance": config.relative_tolerance,
        "base_period": config.base_period,
        "require_label_evidence": config.require_label_evidence,
        "ocr": config.ocr,
        "config_file": os.path.basename(config.source_path) if config.source_path else "",
    }


def review_from_extractions(deck: DeckExtraction, models: list[ModelExtraction], config: Config) -> ReviewResult:
    """Run matching and checks on pre-extracted inputs (no files written). Useful for tests/APIs."""
    warnings: list[ReviewWarning] = list(deck.warnings)
    values = [v for m in models for v in m.values]
    matches = match_deck_to_model(deck.numbers, values, config, slides=deck.slides, warnings=warnings)
    collector = IssueCollector(config)
    build_issues(matches, config, collector, slides=deck.slides)
    run_checks(deck.numbers, matches, deck.slides, deck.footnotes, config, collector)
    issues = finalize_issues(collector.issues, config, slides=deck.slides)
    coverage = compute_coverage(matches, deck)
    _fill_issue_counts(coverage, issues)
    return ReviewResult(issues=issues, matches=matches, warnings=warnings, slides=deck.slides,
                        coverage=coverage, deck_numbers=len(deck.numbers), model_values=len(values))
